    // Honored portraits are earn-only: the shop never lists or sells them, but earlier purchases stay valid.
    internal static bool IsEarnOnlySkin(string id) => id != null
        && (Portraits.Any(row => row.Honored == id) || RetiredHonoredIds.Values.Any(ids => ids.Contains(id)));
