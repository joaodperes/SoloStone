    internal static bool ValidPortraitRow(string hero, string kind, string cardId)
    {
        var definition = Portraits.SingleOrDefault(row => row.Hero == hero);
        if (definition == null || cardId == null) return false;
        if (kind == "golden") return cardId == hero;
        if (kind != "honored") return false;
        return cardId == definition.Honored
            || (RetiredHonoredIds.TryGetValue(hero, out var retired) && retired.Contains(cardId));
    }
    internal static IEnumerable<ClassReward> ActiveRewards => Rewards.Where(row => row.Meta == ActiveMeta);
    private static readonly Lazy<HashSet<string>> Available = new Lazy<HashSet<string>>(() =>
        new HashSet<string>(Cards.All.Where(card => card.Implemented && card.Collectible && LocalCardCatalog.InActiveMeta(card))
            .Select(card => card.Id).Concat(Portraits.Select(row => row.Hero).Where(id => Cards.FromId(id) != null)), StringComparer.Ordinal));
    internal static bool IsAvailable(string id) => id != null && Available.Value.Contains(id);

    internal static int ProgressionAtLeast(LocalProfileData profile, string id, int premium) => Enumerable.Range(1, 3)
        .Where(version => LocalCrafting.PremiumQuality(version) >= LocalCrafting.PremiumQuality(premium))
        .Sum(version => LocalProfile.ProgressionGrantedCount(profile, id, version));

    internal static LocalClassRewardGrant Resolve(LocalProfileData profile, string hero, int level)
    {
        var claimed = profile.ClassRewardGrants.SingleOrDefault(row => row.Hero == hero && row.Level == level);
        if (claimed != null) return Clone(claimed);
        var schedule = ActiveRewards.Where(row => row.Hero == hero).OrderBy(row => row.Level).ToArray();
        var scheduled = schedule.Single(row => row.Level == level);
        var reward = schedule.FirstOrDefault(row => row.Level >= level
            && ProgressionAtLeast(profile, row.CardId, row.Premium) < LocalCrafting.Playset(row.CardId)
            && (row.Level == level || !profile.ClassRewardGrants.Any(grant => grant.CardId == row.CardId
                && LocalCrafting.PremiumQuality(grant.Premium) >= LocalCrafting.PremiumQuality(row.Premium))));
        if (reward == null) return new LocalClassRewardGrant { Hero = hero, Level = level, ScheduledCardId = scheduled.CardId,
            Dust = 400, ScheduleVersion = ScheduleVersion };
        return new LocalClassRewardGrant { Hero = hero, Level = level, CardId = reward.CardId, Premium = reward.Premium,
            Copies = Math.Min(reward.Copies, Math.Max(0, LocalCrafting.Playset(reward.CardId)
                - LocalProfile.ProgressionGrantedCount(profile, reward.CardId, reward.Premium))),
            ScheduledCardId = reward.Level == level ? null : scheduled.CardId, ScheduleVersion = ScheduleVersion };
    }

    internal static LocalClassRewardGrant Clone(LocalClassRewardGrant row) => row == null ? null : new LocalClassRewardGrant {
        Hero = row.Hero, Level = row.Level, CardId = row.CardId, Premium = row.Premium, Copies = row.Copies,
        ScheduleVersion = row.ScheduleVersion, GrantedUtc = row.GrantedUtc, ScheduledCardId = row.ScheduledCardId, Dust = row.Dust
    };

